/** Transient workflows only: does not change the approved Home screen layout.
 * Foreground-only location collection is explicit; this never starts the SOS service.
 */
@Composable
fun MaitriSharingDialog(kind: String, dismiss: () -> Unit) {
    val context = LocalContext.current
    val lifecycle = LocalLifecycleOwner.current.lifecycle
    val p = maitriPalette()
    val scope = rememberCoroutineScope()
    val uid = remember { FirebaseAuth.getInstance().currentUser?.uid }
    val expected = remember(uid) { uid?.let(::ExpectedAccount) }
    val requestStore = remember { context.getSharedPreferences("circle_request_ids", android.content.Context.MODE_PRIVATE) }
    val requestStoreKey = "$uid:$kind"
    var busy by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    var contacts by remember { mutableStateOf<List<CircleContactDto>>(emptyList()) }
    var links by remember { mutableStateOf<List<CircleLinkDto>>(emptyList()) }
    var sessions by remember { mutableStateOf<List<CircleSessionDto>>(emptyList()) }
    var selected by remember { mutableStateOf<Set<String>>(emptySet()) }
    var consent by remember { mutableStateOf(false) }
    var pairConsent by remember { mutableStateOf(false) }
    var ownerEmail by remember { mutableStateOf("") }
    var code by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<PairingCodeDto?>(null) }
    var pairingContact by remember { mutableStateOf<String?>(null) }
    var pairing by remember { mutableStateOf(false) }
    var current by remember { mutableStateOf<CircleSessionDto?>(null) }
    var viewed by remember { mutableStateOf<CircleSessionDto?>(null) }
    var viewingId by remember { mutableStateOf<String?>(null) }
    DisposableEffect(lifecycle) {
        val observer = androidx.lifecycle.LifecycleEventObserver { _, event ->
            if (event == Lifecycle.Event.ON_PAUSE) viewed = null
        }
        lifecycle.addObserver(observer)
        onDispose { lifecycle.removeObserver(observer) }
    }
    DisposableEffect(uid) {
        val auth = FirebaseAuth.getInstance()
        val listener = FirebaseAuth.AuthStateListener { if (it.currentUser?.uid != uid) dismiss() }
        auth.addAuthStateListener(listener)
        onDispose { auth.removeAuthStateListener(listener) }
    }
    var sharingGps by remember { mutableStateOf(false) }
    // Same request and key are retained for an uncertain network retry, including its exact fix.
    var pending by remember { mutableStateOf<Pair<String, CircleShareRequest>?>(null) }
    val permission = rememberLauncherForActivityResult(ActivityResultContracts.RequestMultiplePermissions()) {
        error = if (context.locationAllowed()) "Location allowed. Press confirm to start." else "Location permission is required for trips."
    }

    fun account(): ExpectedAccount {
        if (expected == null || FirebaseAuth.getInstance().currentUser?.uid != uid) throw IOException("Session changed")
        if (BuildConfig.API_BASE_URL.isBlank()) throw IOException("Backend unavailable")
        return expected
    }
    suspend fun refresh() {
        val tag = account()
        requestStore.getString(requestStoreKey, null)?.let { key ->
            try {
                BackendClient.api.circleRequest(key, tag)
                account()
                requestStore.edit().remove(requestStoreKey).apply()
                pending = null
            } catch (e: retrofit2.HttpException) {
                if (e.code() != 404) throw e
            }
        }
        val newContacts = try {
            BackendClient.api.circleContacts(tag)
        } catch (_: Exception) {
            emptyList()
        }
        val newLinks = BackendClient.api.circleLinks(tag)
        val newSessions = BackendClient.api.circleSessions(tag)
        account()
        contacts = newContacts
        links = newLinks
        sessions = newSessions
        current = newSessions.firstOrNull { it.owner && it.kind == "TRIP" && it.status == "ACTIVE" }
    }
    fun run(block: suspend () -> Unit) {
        if (busy) return
        busy = true
        error = null
        scope.launch {
            try { block() }
            catch (e: CancellationException) { throw e }
            catch (e: Exception) { error = circleSharingError(e) }
            finally { busy = false }
        }
    }
    @android.annotation.SuppressLint("MissingPermission") // checked below; callers handle revoked permission
    suspend fun freshFix(): FixDto {
        if (!context.locationAllowed()) throw IOException("Location permission required")
        val cancellation = CancellationTokenSource()
        try {
            val location = withTimeoutOrNull(20000) {
                LocationServices.getFusedLocationProviderClient(context).getCurrentLocation(
                    CurrentLocationRequest.Builder().setPriority(Priority.PRIORITY_HIGH_ACCURACY)
                        .setMaxUpdateAgeMillis(0).build(), cancellation.token).await()
            } ?: throw IOException("Fresh location unavailable")
            if (!location.hasAccuracy()) throw IOException("Location accuracy unavailable")
            return FixDto(location.latitude, location.longitude, Instant.ofEpochMilli(location.time).toString(),
                LocationCompat.isMock(location), location.accuracy.toDouble())
        } finally { cancellation.cancel() }
    }
    LaunchedEffect(uid) {
        run { refresh() }
    }
    LaunchedEffect(sharingGps, current?.id) {
        val id = current?.id ?: return@LaunchedEffect
        if (!sharingGps) return@LaunchedEffect
        lifecycle.repeatOnLifecycle(Lifecycle.State.RESUMED) {
            while (true) {
                try {
                    val fix = freshFix()
                    BackendClient.api.circleFix(id, fix, account())
                    val updated = BackendClient.api.circleSession(id, account())
                    account()
                    current = updated
                } catch (e: CancellationException) { throw e }
                catch (e: Exception) {
                    error = circleSharingError(e)
                    sharingGps = false // bounded retry: user explicitly resumes after error
                    break
                }
                delay(15000)
            }
        }
    }
    LaunchedEffect(viewingId) {
        val id = viewingId ?: return@LaunchedEffect
        lifecycle.repeatOnLifecycle(Lifecycle.State.RESUMED) {
            while (true) {
                // Clear old precise data before refreshing: failure/revocation cannot leave a stale marker.
                viewed = null
                try {
                    val result = BackendClient.api.circleSession(id, account())
                    account()
                    viewed = result
                    delay(15000)
                } catch (e: CancellationException) { throw e }
                catch (e: Exception) { error = circleSharingError(e); break }
            }
        }
    }

    AlertDialog(onDismissRequest = dismiss, containerColor = p.surface,
        titleContentColor = p.primary, textContentColor = p.primary,
        title = { Text(if (kind == "TRIP") "Share my trip" else "Check in") },
        text = {
            Column(Modifier.fillMaxWidth().heightIn(max = 530.dp).verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("Private test sharing with paired accounts. No public link, SOS or SMS is sent.")
                Text("Notifications are available in the recipient’s sharing inbox. Push delivery is not enabled.")
                if (busy) LinearProgressIndicator(Modifier.fillMaxWidth())
                error?.let { Text(it, color = p.accent) }
                TextButton(enabled = !busy, onClick = { run { refresh() } }) { Text("Refresh sharing status") }
                if (kind == "TRIP") current?.let { trip ->
                    Text("Server-confirmed trip: ${trip.status}")
                    Text("Expires: ${trip.expiresAt}")
                    Text("Last server sync: ${trip.syncedAt ?: "No confirmed update"}")
                    Text("GPS updates only while this panel is open and the app is visible. Closing pauses updates; the last fix stays available until stop, revocation or expiry.")
                    TextButton(enabled = !busy, onClick = {
                        if (!context.locationAllowed()) permission.launch(arrayOf(Manifest.permission.ACCESS_FINE_LOCATION, Manifest.permission.ACCESS_COARSE_LOCATION))
                        else sharingGps = !sharingGps
                    }) { Text(if (sharingGps) "Pause location updates" else "Resume foreground location updates") }
                    TextButton(enabled = !busy, onClick = { run {
                        BackendClient.api.stopCircleSession(trip.id, account())
                        account()
                        sharingGps = false
                        refresh()
                    } }) { Text("Stop trip and revoke access") }
                }
                if (kind != "TRIP" || current == null) {
                    Text("Select paired trusted contacts:")
                    links.filter { it.owner }.forEach { link ->
                        Row {
                            Checkbox(checked = link.contactId in selected, enabled = !busy && pending == null,
                                onCheckedChange = { checked ->
                                    selected = if (checked) selected + link.contactId else selected - link.contactId
                                })
                            Text(link.name, Modifier.weight(1f))
                        }
                    }
                    if (links.none { it.owner }) {
                        Text("Pair a trusted contact before sharing.")
                        if (!pairing) {
                            TextButton(onClick = { pairing = true }) {
                                Text("Open pairing setup")
                            }
                        }
                    }
                    Row {
                        Checkbox(checked = consent, enabled = !busy && pending == null, onCheckedChange = { consent = it })
                        Text(if (kind == "TRIP") "I consent to share my precise location with these contacts for 30 minutes."
                            else "Send my check-in timestamp to these contacts. No location is included.", Modifier.weight(1f))
                    }
                    Button(enabled = !busy && consent && selected.isNotEmpty(), onClick = {
                        if (kind == "TRIP" && !context.locationAllowed()) {
                            permission.launch(arrayOf(Manifest.permission.ACCESS_FINE_LOCATION, Manifest.permission.ACCESS_COARSE_LOCATION))
                        } else run {
                            val request = pending ?: ((requestStore.getString(requestStoreKey, null) ?: UUID.randomUUID().toString()) to CircleShareRequest(kind,
                                selected.sorted(), true, if (kind == "TRIP") freshFix() else null)).also { pending = it }
                            // Persist only a random request key, never coordinates, pairing codes or tokens.
                            if (!requestStore.edit().putString(requestStoreKey, request.first).commit())
                                throw IOException("Unable to preserve retry identity")
                            val result = BackendClient.api.createCircleSession(request.first, request.second, account())
                            account()
                            pending = null
                            requestStore.edit().remove(requestStoreKey).apply()
                            consent = false
                            selected = emptySet()
                            refresh()
                            if (result.kind == "TRIP") sharingGps = true
                        }
                    }) { Text(if (pending != null) "Retry unconfirmed request" else if (kind == "TRIP") "Confirm and start trip" else "Confirm check-in") }
                }
                TextButton(onClick = { pairing = !pairing }) { Text(if (pairing) "Hide pairing setup" else "Pair or revoke a trusted account") }
                if (pairing) {
                    Text("Recipient: enter the sender’s verified account email and explicitly consent. Share the temporary code privately with that person.")
                    OutlinedTextField(ownerEmail, { ownerEmail = it }, label = { Text("Sender account email") }, singleLine = true)
                    Row { Checkbox(pairConsent, { pairConsent = it }); Text("I consent to receive private sharing from this account.", Modifier.weight(1f)) }
                    TextButton(enabled = !busy && pairConsent && ownerEmail.isNotBlank(), onClick = { run {
                        generated = BackendClient.api.circlePairingCode(PairingRequestDto(ownerEmail.trim()), account())
                        account()
                    } }) { Text("Generate private pairing code") }
                    generated?.let { pair -> SelectionContainer { Text("Code: ${pair.code}\nExpires: ${pair.expiresAt}") } }
                    Text("Sender: select the saved contact and paste the code they gave you.")
                    contacts.forEach { contact ->
                        Row { RadioButton(pairingContact == contact.id, { pairingContact = contact.id }); Text(contact.name) }
                    }
                    OutlinedTextField(code, { code = it }, label = { Text("Private pairing code") }, singleLine = true)
                    TextButton(enabled = !busy && pairingContact != null && code.isNotBlank(), onClick = { run {
                        BackendClient.api.bindCircle(BindCircleDto(requireNotNull(pairingContact), code.trim()), account())
                        account()
                        code = ""
                        refresh()
                    } }) { Text("Confirm contact pairing") }
                    links.forEach { link ->
                        TextButton(enabled = !busy, onClick = { run {
                            BackendClient.api.revokeCircle(link.id, account())
                            viewingId = null
                            viewed = null
                            refresh()
                        } }) { Text("Revoke pairing: ${link.name}") }
                    }
                }
                Text("Sharing inbox and recent activity")
                sessions.forEach { session ->
                    Text("${if (session.owner) "Sent" else "Received"} ${session.kind}: ${session.status}\n${session.createdAt}")
                    if (session.owner) {
                        session.recipients.forEach { recipient -> Text(if (recipient.revoked) "Recipient access revoked" else circleReceiptLabel(recipient.status)) }
                    } else {
                        TextButton(enabled = !busy, onClick = { run {
                            viewed = null
                            val result = BackendClient.api.circleSession(session.id, account())
                            BackendClient.api.openCircleSession(session.id, account())
                            account()
                            viewed = result
                            viewingId = result.id
                        } }) { Text("Open authorized update") }
                    }
                }
                viewed?.let { session ->
                    Text("Authorized ${session.kind}: ${session.status}")
                    Text("Server timestamp: ${session.createdAt}")
                    session.fix?.let { fix ->
                        Text("Location recorded: ${fix.recordedAt}\nLatitude: ${fix.latitude}\nLongitude: ${fix.longitude}\nAccuracy: ${fix.accuracyMeters} m")
                    }
                }
            }
        },
        confirmButton = { TextButton(onClick = dismiss) { Text("Close") } })
}
