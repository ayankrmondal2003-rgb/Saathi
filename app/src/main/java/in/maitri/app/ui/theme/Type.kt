/**
 * Inter, the typeface of the design boards (res/font/inter.ttf, variable weight; SIL Open Font License, see
 * assets/licenses/Inter-OFL.txt). Scripts Inter doesn't cover (Devanagari, Bengali, Tamil, Telugu) fall back to the
 * phone's own fonts glyph by glyph.
 */
